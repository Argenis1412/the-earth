const displayNames = new Intl.DisplayNames(['en'], { type: 'region' });

const NAME_EN = {};
const CAPITAL_EN = {};
for (const country of COUNTRY_DETAILS) {
  const iso2 = country.iso2;
  if (!iso2) continue;
  NAME_EN[iso2] = NAME_OVERRIDES[iso2] || displayNames.of(iso2);
  CAPITAL_EN[iso2] = CAPITAL_OVERRIDES[country.capital] || country.capital;
}

const missingLanguages = [...new Set(COUNTRY_DETAILS.flatMap((c) => c.languages))].filter(
  (language) => !LANGUAGE_EN[language],
);
const missingCurrencies = [...new Set(COUNTRY_DETAILS.map((c) => c.currency))].filter(
  (currency) => !CURRENCY_EN[currency],
);
const missingContinents = [...new Set(COUNTRY_DETAILS.map((c) => c.continent))].filter(
  (continent) => !CONTINENT_EN[continent],
);

if (missingLanguages.length || missingCurrencies.length || missingContinents.length) {
  throw new Error(
    [
      missingLanguages.length && `Missing languages: ${missingLanguages.join(', ')}`,
      missingCurrencies.length && `Missing currencies: ${missingCurrencies.join(', ')}`,
      missingContinents.length && `Missing continents: ${missingContinents.join(', ')}`,
    ]
      .filter(Boolean)
      .join('\n'),
  );
}

const serialize = (object) =>
  Object.entries(object)
    .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
    .join('\n');

const output = `/**
 * English translations for the country catalogue, keyed by ISO-2 code or by the
 * Spanish value used as the translation key.
 * Generated by scripts/gen-country-i18n.mjs.
 */
export const NAME_EN = {
${serialize(NAME_EN)}
};

export const NAME_EN_BY_NAME = {
${serialize(NAME_BY_NAME)}
};

export const CAPITAL_EN = {
${serialize(CAPITAL_EN)}
};

export const CAPITAL_EN_BY_NAME = {
${serialize(CAPITAL_BY_NAME)}
};

export const LANGUAGE_EN = {
${serialize(LANGUAGE_EN)}
};

export const CURRENCY_EN = {
${serialize(CURRENCY_EN)}
};

export const CONTINENT_EN = {
${serialize(CONTINENT_EN)}
};
`;

writeFileSync(new URL('../src/data/countryDetails.en.js', import.meta.url), output);
console.log(
  `Wrote ${Object.keys(NAME_EN).length} names, ${Object.keys(LANGUAGE_EN).length} languages, ${Object.keys(CURRENCY_EN).length} currencies.`,
);
